/**
 * WhatsApp Real Vertical Slice Verification Script
 *
 * Verifies the complete Caregiver Lifecycle:
 * approved test phone -> inbound greeting -> delivered OTP -> verification
 * -> explicit consent -> persisted subscription -> reply -> STOP persisted.
 *
 * Safety & Privacy Boundaries:
 * - Requires explicit APPROVED_TEST_RECIPIENT_PHONE env var or safe synthetic fallback
 * - Masked phone numbers in all output (+91 ******6789)
 * - Zero plaintext OTP storage or output in audit logs
 * - Distinguishes real Meta Graph API sends from simulated sends based on ALLOW_LIVE_WHATSAPP_SEND
 * - Uses durable Supabase stores when SUPABASE_URL & SUPABASE_SERVICE_ROLE_KEY are present
 * - Safe for dry-run and live pre-flight checks
 */

import { getAppEnvConfig } from '../src/lib/server/envConfig';
import {
  getCaregiverSubscriptionStore,
  getCaregiverSubscriptionStateMachine,
  getWhatsAppOutboundSender,
} from '../src/lib/server/whatsappPipelineFactory';

async function main() {
  console.log('================================================================');
  console.log('WHATSAPP VERTICAL SLICE PRE-FLIGHT & EXECUTION HARNESS');
  console.log('================================================================\n');

  const env = getAppEnvConfig();
  const testPhone = process.env.APPROVED_TEST_RECIPIENT_PHONE || '+919988776655';
  const isApprovedLiveSend = env.allowLiveWhatsAppSend;

  console.log(`[CONFIG] Environment: ${env.isProduction ? 'PRODUCTION' : 'DEVELOPMENT/PREVIEW'}`);
  console.log(`[CONFIG] Live Outbound Allowed (ALLOW_LIVE_WHATSAPP_SEND): ${isApprovedLiveSend}`);
  console.log(`[CONFIG] Meta Access Token Configured: ${Boolean(env.metaAccessToken)}`);
  console.log(`[CONFIG] Meta Phone Number ID: ${env.metaPhoneNumberId || 'NOT_CONFIGURED'}`);
  console.log(`[CONFIG] Supabase URL Configured: ${Boolean(env.supabaseUrl)}`);
  console.log(`[CONFIG] Supabase Service Role Key Configured: ${Boolean(env.supabaseServiceRoleKey)}`);
  console.log(`[CONFIG] Target Test Recipient: ${testPhone.replace(/(\+\d{2})\d{6}(\d{4})/, '$1 ****** $2')}\n`);

  if (!isApprovedLiveSend) {
    console.log('ℹ️  NOTE: ALLOW_LIVE_WHATSAPP_SEND=false. All outbound dispatches will use simulated wamid responses.');
    console.log('   To enable live Meta Cloud API dispatch to the verified test number, set ALLOW_LIVE_WHATSAPP_SEND=true.\n');
  }

  const store = getCaregiverSubscriptionStore();
  const stateMachine = getCaregiverSubscriptionStateMachine();
  const outboundSender = getWhatsAppOutboundSender();

  const phoneHash = stateMachine.hashPhoneNumber(testPhone);
  const syntheticChildId = 'CH-TEST-SLICE-001';
  const syntheticSubmissionId = 'sub-test-slice-001';

  console.log('--- STEP 1: Link Beneficiary Submission ---');
  const linked = await stateMachine.linkBeneficiary(testPhone, syntheticChildId, syntheticSubmissionId);
  console.log(`✓ Beneficiary linked: state=${linked.state}, maskedPhone=${linked.phoneMasked}`);

  console.log('\n--- STEP 2: Inbound Greeting -> OTP Challenge Initiated ---');
  const greetingResult = await stateMachine.handleInboundMessage({
    fromPhone: testPhone,
    messageId: `msg_slice_greet_${Date.now()}`,
    textBody: 'Namaste',
  });
  console.log(`✓ State Transition: ${greetingResult.record.state}`);
  console.log(`✓ Template Name: ${greetingResult.response?.templateName}`);

  const rawOtp = greetingResult.rawOtpForTransport;
  if (!rawOtp) {
    throw new Error('FAILED: OTP code was not generated by state machine.');
  }
  console.log('✓ Single-use OTP generated (masked for security)');

  // Dispatch OTP via Outbound Sender
  const otpDispatchResult = await outboundSender.dispatch(
    {
      idempotencyKey: `slice-otp-send-${Date.now()}`,
      correlationId: `corr-slice-otp-${Date.now()}`,
      recipientPhoneE164: testPhone,
      messageType: 'TEXT',
      textBody: `Your Child Nutrition Programme verification code is: ${rawOtp}\n\nValid for 10 minutes. Do not share this code.`,
    },
    { userId: 'system-slice-runner', role: 'SYSTEM' }
  );
  console.log(`✓ Outbound OTP Dispatch: status=${otpDispatchResult.status}, wamid=${otpDispatchResult.wamid || 'simulated'}`);

  console.log('\n--- STEP 3: OTP Verification -> State Transition to VERIFIED ---');
  const verifyResult = await stateMachine.handleInboundMessage({
    fromPhone: testPhone,
    messageId: `msg_slice_verify_${Date.now()}`,
    textBody: rawOtp,
  });
  console.log(`✓ State Transition: ${verifyResult.record.state} (Consent Provided: ${verifyResult.record.consentProvided})`);
  if (verifyResult.record.state !== 'VERIFIED') {
    throw new Error(`FAILED: Expected state VERIFIED, got ${verifyResult.record.state}`);
  }
  console.log('✓ INVARIANT UPHELD: Proof of phone possession does NOT auto-subscribe');

  console.log('\n--- STEP 4: Explicit Affirmative Consent -> State Transition to SUBSCRIBED ---');
  const consentResult = await stateMachine.handleInboundMessage({
    fromPhone: testPhone,
    messageId: `msg_slice_consent_${Date.now()}`,
    textBody: 'YES',
  });
  console.log(`✓ State Transition: ${consentResult.record.state}`);
  console.log(`✓ Consent Recorded: ${consentResult.record.consentProvided} at ${consentResult.record.consentRecordedAt}`);
  if (consentResult.record.state !== 'SUBSCRIBED') {
    throw new Error(`FAILED: Expected state SUBSCRIBED, got ${consentResult.record.state}`);
  }

  // Dispatch Welcome confirmation
  if (consentResult.response?.textBody) {
    const welcomeDispatch = await outboundSender.dispatch(
      {
        idempotencyKey: `slice-welcome-send-${Date.now()}`,
        correlationId: `corr-slice-welcome-${Date.now()}`,
        recipientPhoneE164: testPhone,
        messageType: 'TEXT',
        textBody: consentResult.response.textBody,
      },
      { userId: 'system-slice-runner', role: 'SYSTEM' }
    );
    console.log(`✓ Outbound Subscription Confirmation: status=${welcomeDispatch.status}`);
  }

  console.log('\n--- STEP 5: Opt-Out ("STOP") -> State Transition to OPTED_OUT ---');
  const stopResult = await stateMachine.handleInboundMessage({
    fromPhone: testPhone,
    messageId: `msg_slice_stop_${Date.now()}`,
    textBody: 'STOP',
  });
  console.log(`✓ State Transition: ${stopResult.record.state}`);
  console.log(`✓ Opt-Out Reason: ${stopResult.record.optOutReason}`);
  const isOptedOutInStore = await store.isOptedOut(phoneHash);
  console.log(`✓ Opt-Out Store Check: ${isOptedOutInStore ? 'CONFIRMED' : 'FAILED'}`);

  if (stopResult.record.state !== 'OPTED_OUT' || !isOptedOutInStore) {
    throw new Error('FAILED: Opt-out was not properly persisted.');
  }

  console.log('\n================================================================');
  console.log('✓ VERTICAL SLICE EXECUTION COMPLETED SUCCESSFULLY');
  console.log('================================================================');
}

main().catch((err) => {
  console.error('\n❌ Vertical slice execution failed:', err);
  process.exit(1);
});
