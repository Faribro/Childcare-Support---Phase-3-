export function validatePinCodeMatch(pinCode: string, state: string): { valid: boolean; message?: string } {
  const cleanPin = (pinCode || '').trim();
  if (!/^[1-9][0-9]{5}$/.test(cleanPin)) {
    return { valid: false, message: 'Pin code must be exactly 6 digits and cannot start with 0.' };
  }
  const canonical = getCanonicalState(state);
  if (!canonical) {
    return { valid: true }; // Cannot verify without valid state
  }
  const allowedPrefixes = POSTAL_CIRCLE_PREFIXES[canonical];
  if (!allowedPrefixes) {
    return { valid: true };
  }
  const prefix = cleanPin.substring(0, 2);
  const match = allowedPrefixes.includes(prefix);
  if (!match) {
    return {
      valid: false,
      message: `Pin code prefix "${prefix}" does not typically correspond to ${canonical}. Please verify the state and pin code.`
    };
  }
  return { valid: true };
}
