import { describe, it, expect, beforeEach } from 'vitest';
import { FirestoreOtpStore } from '@/lib/server/firestoreOtpStore';
import { DistributedFirestoreOtpProvider } from '@/lib/server/otpgatewayAdapter';

describe('Multi-Instance Distributed OTP Challenge Verification & Safety', () => {
  let sharedStore: FirestoreOtpStore;
  let instanceA: DistributedFirestoreOtpProvider;
  let instanceB: DistributedFirestoreOtpProvider;

  beforeEach(async () => {
    sharedStore = new FirestoreOtpStore();
    await sharedStore.resetForTesting();
    instanceA = new DistributedFirestoreOtpProvider({ store: sharedStore });
    instanceB = new DistributedFirestoreOtpProvider({ store: sharedStore });
  });

  it('allows Instance B to verify an OTP challenge generated by Instance A', async () => {
    const mobile = '+919876543210';
    const reqResult = await instanceA.sendOtp(mobile, 'login');

    expect(reqResult.success).toBe(true);
    expect(reqResult.maskedMobile).toBe('+91 ******3210');
    expect(reqResult.debugCode).toBeDefined();

    const otpCode = reqResult.debugCode!;

    // Instance B receives the verify call from the client
    const verifyResult = await instanceB.verifyOtp(mobile, otpCode, 'login');
    expect(verifyResult.success).toBe(true);
    expect(verifyResult.canonicalMobile).toBe(mobile);
  });

  it('strictly enforces atomic single-use: replay attempts across instances fail with ALREADY_USED', async () => {
    const mobile = '+919876543210';
    const reqResult = await instanceA.sendOtp(mobile, 'login');
    const otpCode = reqResult.debugCode!;

    // Instance B verifies and consumes the OTP
    const firstVerify = await instanceB.verifyOtp(mobile, otpCode, 'login');
    expect(firstVerify.success).toBe(true);

    // Instance A receives a replayed/duplicate verify call
    const replayVerify = await instanceA.verifyOtp(mobile, otpCode, 'login');
    expect(replayVerify.success).toBe(false);
    expect(replayVerify.code).toBe('ALREADY_USED');
    expect(replayVerify.error).toContain('already been verified and consumed');
  });

  it('enforces shared 60-second cooldown across all Cloud Run instances', async () => {
    const mobile = '+919876543210';
    const firstReq = await instanceA.sendOtp(mobile, 'login');
    expect(firstReq.success).toBe(true);

    // Instance B immediately receives a second sendOtp request
    const secondReq = await instanceB.sendOtp(mobile, 'login');
    expect(secondReq.success).toBe(false);
    expect(secondReq.error).toBe('COOLDOWN_ACTIVE');
    expect(secondReq.retryAfterSeconds).toBeGreaterThan(0);
    expect(secondReq.message).toContain('Please wait');
  });

  it('shares failed-attempt counters across instances and locks challenge on 3 wrong tries', async () => {
    const mobile = '+919876543210';
    const reqResult = await instanceA.sendOtp(mobile, 'login');
    expect(reqResult.success).toBe(true);

    // Wrong attempt 1 on Instance A
    const attempt1 = await instanceA.verifyOtp(mobile, '000000', 'login');
    expect(attempt1.success).toBe(false);
    expect(attempt1.code).toBe('INVALID_CODE');
    expect(attempt1.remainingAttempts).toBe(2);

    // Wrong attempt 2 on Instance B
    const attempt2 = await instanceB.verifyOtp(mobile, '111111', 'login');
    expect(attempt2.success).toBe(false);
    expect(attempt2.code).toBe('INVALID_CODE');
    expect(attempt2.remainingAttempts).toBe(1);

    // Wrong attempt 3 on Instance A -> Locked out
    const attempt3 = await instanceA.verifyOtp(mobile, '222222', 'login');
    expect(attempt3.success).toBe(false);
    expect(attempt3.code).toBe('MAX_ATTEMPTS_EXCEEDED');
    expect(attempt3.remainingAttempts).toBe(0);

    // Subsequent attempt even with correct code is rejected
    const attemptAfterLock = await instanceB.verifyOtp(mobile, reqResult.debugCode!, 'login');
    expect(attemptAfterLock.success).toBe(false);
  });

  it('fails closed safely without leaking PII or secrets when database encounters an error', async () => {
    const brokenDb = {
      collection: () => {
        throw new Error('Firestore connection timeout');
      },
      runTransaction: async () => {
        throw new Error('Firestore connection timeout');
      },
    };

    const faultyStore = new FirestoreOtpStore({ customDb: brokenDb });
    const faultyInstance = new DistributedFirestoreOtpProvider({ store: faultyStore });

    const reqResult = await faultyInstance.sendOtp('+919876543210', 'login');
    expect(reqResult.success).toBe(false);
    expect(reqResult.error).toBe('DATABASE_UNAVAILABLE');
    // Ensure no phone or secrets leaked
    expect(reqResult.message).not.toContain('+919876543210');

    const verifyResult = await faultyInstance.verifyOtp('+919876543210', '123456', 'login');
    expect(verifyResult.success).toBe(false);
    expect(verifyResult.code).toBe('DATABASE_UNAVAILABLE');
  });
});
